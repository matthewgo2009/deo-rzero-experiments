"""Re-label canonical iter 2's filtered dataset with solver_v1 (the eval-76.8
model). Also re-run base M-vote on the same. Save per-entry comparison to a
new file so we can see whether solver_v1's M-vote majority matches the stored
pseudo more often than base's, and how p_hat compares.

Stored pseudo in canonical iter 2 was generated by solver_v1 at the time iter
2 was created (since solver_v1 was the current solver). So solver_v1's match
rate here is essentially a "self-consistency under fresh sampling" check.

Output: /eph/nvme0/yyd/DEO/iter2_relabel_comparison.json
   plus summary stats printed to stdout.
"""
import json
import os
import re
import sys
import time
import requests
from collections import Counter
from concurrent.futures import ThreadPoolExecutor

TRAINING_SET = "/eph/nvme0/yyd/paper_data/DEO/filtered_datasets/filtered_deo_qwen3_4b_base_solver_v2.json"
OUTPUT = "/eph/nvme0/yyd/DEO/iter2_relabel_comparison.json"
BASE_URL = "http://localhost:8000/v1/completions"        # vllm_base
SOLVER_URL = "http://localhost:8001/v1/completions"      # vllm_solver_check loaded with solver_v1
MODEL_NAME = "Qwen/Qwen3-4B-Base"
M_SAMPLES = 9
SYSTEM_PROMPT = r"Please reason step by step, and put your final answer within \boxed{}."
MAX_TOKENS = 4096
CHUNK_PROMPTS = 1800  # 200 questions * 9 samples per HTTP call

_BOXED_RE = re.compile(r"\\boxed\{")


def extract_boxed(text):
    if not text:
        return None
    starts = [m.end() for m in _BOXED_RE.finditer(text)]
    if not starts:
        return None
    pos, depth, out = starts[-1], 1, []
    while pos < len(text) and depth > 0:
        c = text[pos]
        if c == "{":
            depth += 1; out.append(c)
        elif c == "}":
            depth -= 1
            if depth == 0:
                break
            out.append(c)
        else:
            out.append(c)
        pos += 1
    return ("".join(out).strip()) or None if depth == 0 else None


def build_chat_prompt(question):
    return (
        f"<|im_start|>system\n{SYSTEM_PROMPT}<|im_end|>\n"
        f"<|im_start|>user\n{question}<|im_end|>\n"
        f"<|im_start|>assistant\n"
    )


def call_chunked(endpoint, prompts, label):
    """Send prompts to vllm completions endpoint in chunks. Returns ordered list of texts."""
    out = []
    for i in range(0, len(prompts), CHUNK_PROMPTS):
        chunk = prompts[i:i + CHUNK_PROMPTS]
        t0 = time.time()
        r = requests.post(endpoint, json={
            "model": MODEL_NAME, "prompt": chunk,
            "max_tokens": MAX_TOKENS, "temperature": 1.0,
            "top_p": 1.0, "top_k": 40,
        }, timeout=1800)
        r.raise_for_status()
        out.extend(c["text"] for c in r.json()["choices"])
        elapsed = time.time() - t0
        print(f"  [{label}] chunk {i // CHUNK_PROMPTS + 1}: {len(chunk)} prompts in {elapsed:.0f}s "
              f"({len(chunk)/elapsed:.1f} prompts/s)")
    return out


def m_vote(endpoint, questions, label):
    """Return list of (majority, p_hat) for each question, plus raw answers."""
    prompts = [build_chat_prompt(q) for q in questions for _ in range(M_SAMPLES)]
    texts = call_chunked(endpoint, prompts, label)
    answers = [extract_boxed(t) for t in texts]
    out = []
    for i in range(len(questions)):
        chunk = answers[i * M_SAMPLES: (i + 1) * M_SAMPLES]
        valid = [a for a in chunk if a is not None]
        if not valid:
            out.append((None, 0.0))
            continue
        major, count = Counter(valid).most_common(1)[0]
        out.append((major, count / M_SAMPLES))
    return out


def normalize(s):
    """Cheap string match (boxed answers are usually short literals)."""
    if s is None:
        return ""
    return str(s).strip().replace(" ", "")


def main():
    with open(TRAINING_SET) as f:
        entries = json.load(f)
    print(f"Loaded {len(entries)} entries from canonical iter 2 filtered dataset")

    questions = [e["problem"] for e in entries]
    stored = [(e["answer"], float(e["score"])) for e in entries]

    # Run base + solver_v1 in parallel (different endpoints).
    print("\n=== M-vote: base ===")
    with ThreadPoolExecutor(max_workers=2) as ex:
        f_base = ex.submit(m_vote, BASE_URL, questions, "base")
        f_solver = ex.submit(m_vote, SOLVER_URL, questions, "solver_v1")
        base_results = f_base.result()
        solver_results = f_solver.result()
    print("=== M-vote: solver_v1 ===")

    # Aggregate stats
    n = len(entries)
    base_match = solver_match = 0
    base_no_ext = solver_no_ext = 0
    base_phats, solver_phats = [], []
    out_rows = []
    for i, e in enumerate(entries):
        stored_ans = stored[i][0]
        b_pseudo, b_phat = base_results[i]
        s_pseudo, s_phat = solver_results[i]
        if b_pseudo is None:
            base_no_ext += 1
        if s_pseudo is None:
            solver_no_ext += 1
        b_match = normalize(b_pseudo) == normalize(stored_ans)
        s_match = normalize(s_pseudo) == normalize(stored_ans)
        if b_match:
            base_match += 1
        if s_match:
            solver_match += 1
        base_phats.append(b_phat)
        solver_phats.append(s_phat)
        out_rows.append({
            "problem": e["problem"],
            "stored_answer": stored_ans,
            "stored_score": stored[i][1],
            "base_pseudo": b_pseudo,
            "base_p_hat": b_phat,
            "base_matches_stored": b_match,
            "solver_v1_pseudo": s_pseudo,
            "solver_v1_p_hat": s_phat,
            "solver_v1_matches_stored": s_match,
        })

    summary = {
        "n_entries": n,
        "stored_pseudo_p_hat_mean": sum(s for _, s in stored) / n,
        "base": {
            "match_rate_vs_stored": base_match / n,
            "n_match": base_match,
            "mean_p_hat": sum(base_phats) / n,
            "no_extract": base_no_ext,
        },
        "solver_v1": {
            "match_rate_vs_stored": solver_match / n,
            "n_match": solver_match,
            "mean_p_hat": sum(solver_phats) / n,
            "no_extract": solver_no_ext,
        },
    }

    with open(OUTPUT, "w") as f:
        json.dump({"summary": summary, "entries": out_rows}, f, indent=2, ensure_ascii=False)

    print("\n" + "=" * 60)
    print("ITER 2 RELABEL COMPARISON SUMMARY")
    print("=" * 60)
    print(f"{'metric':<35s} {'base':>10s} {'solver_v1':>10s}")
    print(f"{'match rate vs stored pseudo':<35s} "
          f"{summary['base']['match_rate_vs_stored']*100:>9.1f}% "
          f"{summary['solver_v1']['match_rate_vs_stored']*100:>9.1f}%")
    print(f"{'mean p_hat (M-vote consistency)':<35s} "
          f"{summary['base']['mean_p_hat']:>10.3f} "
          f"{summary['solver_v1']['mean_p_hat']:>10.3f}")
    print(f"{'no-extract':<35s} "
          f"{summary['base']['no_extract']:>10d} "
          f"{summary['solver_v1']['no_extract']:>10d}")
    print(f"\nFull per-entry file: {OUTPUT}")
    print(f"Stored p_hat mean: {summary['stored_pseudo_p_hat_mean']:.3f}")


if __name__ == "__main__":
    main()
